/** Days since 1970-01-01 in Indonesia (UTC+7), so the verse changes at local midnight. */
export function jakartaDay(now = Date.now()) {
  return Math.floor((now + 7 * 3600 * 1000) / 86400000);
}

/** Same verse for everyone on a given day; walks through the whole pool before repeating. */
export function verseOfDayIndex(day = jakartaDay()) {
  // Spread consecutive days across the pool (coprime step) so neighbours aren't from the same book
  const step = 37;
  return ((day * step) % VOTD_POOL.length + VOTD_POOL.length) % VOTD_POOL.length;
}
